#!/usr/bin/env python3
"""Convert extracted PPG Wave 2.3 ROM data into a t00t-native C++ header.

Input: extract/w23_waves.bin (244 raw 8-bit unsigned waveforms, 64 samples
each) and extract/w23_wavetables.json (29 wavetable keyframe-index records)
-- see README.md's "ROM wavetable format" for provenance and the format.

Output: a single header (default src/engines/wavetable/ppg_waves.h) with
everything baked in as `const` data:

  - PPG_WAVE_COUNT waveforms, PPG_WAVE_SIZE samples each, converted from the
    ROM's 8-bit unsigned PCM to the signed 16-bit range
    src/osc/wavetable.h's WaveTable.keyframes expects ((byte - 128) << 8).
  - PPG_WAVETABLE_COUNT wavetables, each pre-expanded to a full
    WT_INDEX_SIZE-entry osc/wavetable.h WaveTableIndexEntry array --
    the keyframe -> 64-position interpolation (linear between each
    table's authored (wave, slot) pairs, held flat past the last slot) is
    computed here, offline, once, so the device never runs this expansion
    at init time -- same "precompute at conversion time, ship a flat
    lookup table" idiom as tools/xm2t00t's period tables
    (module_tracker.md's Song Blob Format section).

This mirrors tools/syx2patch.py's role for the FM module: output is
git-ignored (see repo .gitignore's `tools/ppg/` entry, extended below to
cover the header itself) because it's derived from third-party ROM content,
regenerated locally rather than checked in. The wavetable engine's
tables.h falls back to its own procedurally-generated tables when this
header hasn't been generated -- see that file's own T00T_WT_HAS_PPG_WAVES
gate.

Usage:
  python3 tools/ppg/convert_ppg_waves.py \\
      tools/ppg/extract/w23_waves.bin tools/ppg/extract/w23_wavetables.json \\
      src/engines/wavetable/ppg_waves.h
"""
import json
import sys

WAVE_BYTES = 64
WT_INDEX_SIZE = 64  # must match src/osc/wavetable.h's WT_INDEX_SIZE


def load_waves(path, expected_count):
    with open(path, "rb") as f:
        data = f.read()
    assert len(data) == expected_count * WAVE_BYTES, (
        f"{path}: expected {expected_count * WAVE_BYTES} bytes, got {len(data)}"
    )
    return [data[i * WAVE_BYTES:(i + 1) * WAVE_BYTES] for i in range(expected_count)]


def expand_table(keys, num_waves):
    """keys: list of {"wave": int, "slot": int}, slot ascending, keys[0].slot
    == 0, keys[-1].slot == 0x3C (per README's confirmed format). Returns a
    WT_INDEX_SIZE-entry list of (wave_a, wave_b, blend) -- blend is Q8,
    0 = pure wave_a, 255 = pure wave_b."""
    out = []
    last_slot = keys[-1]["slot"]
    for i in range(WT_INDEX_SIZE):
        if i >= last_slot:
            w = keys[-1]["wave"]
            out.append((w, w, 0))
            continue
        # Find the bracketing pair (lo, hi) with lo.slot <= i < hi.slot.
        lo, hi = keys[0], keys[-1]
        for j in range(len(keys) - 1):
            if keys[j]["slot"] <= i < keys[j + 1]["slot"]:
                lo, hi = keys[j], keys[j + 1]
                break
        span = hi["slot"] - lo["slot"]
        frac = (i - lo["slot"]) / span if span else 0.0
        wave_a = lo["wave"]
        wave_b = hi["wave"]
        blend = round(frac * 255)
        # Clamp waveform indices the ROM references but this dump doesn't
        # have (README's "Wavetable 13 references waveforms 244 and 245" --
        # an EVU-expansion-board quirk) to the last real waveform, rather
        # than reading out of bounds.
        if wave_a >= num_waves: wave_a = num_waves - 1
        if wave_b >= num_waves: wave_b = num_waves - 1
        out.append((wave_a, wave_b, blend))
    return out


def main():
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} <w23_waves.bin> <w23_wavetables.json> <out.h>", file=sys.stderr)
        sys.exit(1)
    waves_path, tables_path, out_path = sys.argv[1:4]

    with open(tables_path) as f:
        tdata = json.load(f)
    num_waves = tdata["num_waves"]
    assert tdata["wave_bytes"] == WAVE_BYTES
    waves = load_waves(waves_path, num_waves)
    tables = tdata["tables"]

    for t in tables:
        for k in t["keys"]:
            if k["wave"] >= num_waves:
                print(f"warning: wavetable {t['table']} references waveform "
                      f"{k['wave']} (only {num_waves} exist) -- clamping to "
                      f"{num_waves - 1}", file=sys.stderr)

    expanded = [expand_table(t["keys"], num_waves) for t in tables]

    with open(out_path, "w") as f:
        f.write("// Generated by tools/ppg/convert_ppg_waves.py from PPG Wave 2.3\n")
        f.write("// ROM data (tools/ppg/rom/, tools/ppg/extract/) -- do not edit by hand.\n")
        f.write("// See tools/ppg/README.md for provenance and format notes.\n")
        f.write("#pragma once\n\n#include <cstdint>\n")
        f.write('#include "../../osc/wavetable.h"  // WaveTableIndexEntry\n\n')

        f.write(f"static constexpr uint16_t PPG_WAVE_COUNT = {num_waves};\n")
        f.write(f"static constexpr uint16_t PPG_WAVE_SIZE = {WAVE_BYTES};\n")
        f.write(f"static constexpr uint16_t PPG_WAVETABLE_COUNT = {len(tables)};\n\n")

        f.write("// (byte - 128) << 8 -- ROM's 8-bit unsigned PCM, converted to the\n")
        f.write("// signed 16-bit range src/osc/wavetable.h's WaveTable.keyframes expects.\n")
        f.write(f"inline const int16_t ppg_wave_data[PPG_WAVE_COUNT * PPG_WAVE_SIZE] = {{\n")
        for w in waves:
            row = ", ".join(str((b - 128) << 8) for b in w)
            f.write(f"    {row},\n")
        f.write("};\n\n")

        f.write("// Pre-expanded to WT_INDEX_SIZE entries per table (src/osc/wavetable.h's\n")
        f.write("// WaveTableIndexEntry shape: wave_a, wave_b, blend) -- the keyframe ->\n")
        f.write("// 64-position interpolation is baked in at conversion time, never\n")
        f.write("// recomputed on device.\n")
        f.write(f"inline const WaveTableIndexEntry ppg_wavetable_index[PPG_WAVETABLE_COUNT][{WT_INDEX_SIZE}] = {{\n")
        for entries in expanded:
            f.write("    {")
            f.write(", ".join(f"{{{a},{b},{c}}}" for a, b, c in entries))
            f.write("},\n")
        f.write("};\n")

    total_bytes = num_waves * WAVE_BYTES * 2 + len(tables) * WT_INDEX_SIZE * 3
    print(f"wrote {out_path}: {num_waves} waveforms, {len(tables)} wavetables "
          f"(~{total_bytes} bytes of const data)")


if __name__ == "__main__":
    main()
