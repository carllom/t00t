// Generates src/engines/subtractive/factory_bank.h -- the subtractive
// factory bank as stored-format Patches -- from the const preset tables in
// src/engines/subtractive/presets.h.
//
//   gen_subtractive_bank <out.h>            # write the header
//   gen_subtractive_bank --check <file.h>   # exit 1 if <file.h> is stale
//
// Each preset is converted to Descriptor values, and the conversion is
// checked to be lossless: cooking the values must give exactly the
// constants the preset itself implies.

#include "presets.h"
#include "patch.h"
#include "patch/stored_format.h"

#include <cmath>
#include <cstdio>
#include <cstring>
#include <string>

namespace {

bool g_ok = true;

void fail(uint32_t i, const char *what) {
    fprintf(stderr, "preset %u (%s): %s\n", i, preset_names[i], what);
    g_ok = false;
}

// A preset float that must be an exact multiple of 1/scale.
int32_t to_int(uint32_t i, float x, float scale, const char *what) {
    float scaled = x * scale;
    long r = lroundf(scaled);
    if (fabsf(scaled - (float)r) > 1e-4f || (float)r / scale != x) fail(i, what);
    return (int32_t)r;
}

void to_values(uint32_t i, const VoicePreset &pr, int32_t (&v)[SUB_P_COUNT]) {
    v[SUB_P_WAVEFORM] = pr.waveform;
    v[SUB_P_SAMPLE] = 0;
    if (pr.waveform == WAVE_SAMPLE) {
        bool found = false;
        for (uint32_t s = 0; s < SUB_SAMPLE_COUNT; s++) {
            if (kSubSamples[s] == pr.sample) { v[SUB_P_SAMPLE] = (int32_t)s; found = true; }
        }
        if (!found) fail(i, "sample not in kSubSamples");
    }
    v[SUB_P_DUTY] = pr.duty_cycle;
    v[SUB_P_LFO_RATE] = to_int(i, pr.lfo_rate, 100.0f, "lfo_rate not a multiple of 0.01 Hz");
    v[SUB_P_LFO_AMP] = to_int(i, pr.lfo_depth, 1000.0f, "lfo_depth not a multiple of 0.001");
    v[SUB_P_LFO_PITCH] = to_int(i, pr.lfo_pitch_depth, 1000.0f, "lfo_pitch_depth not a multiple of 0.001");
    v[SUB_P_LFO_PWM] = to_int(i, pr.lfo_pwm_depth, 1000.0f, "lfo_pwm_depth not a multiple of 0.001");
    v[SUB_P_LFO_CUTOFF] = to_int(i, pr.lfo_filter_depth, 1.0f, "lfo_filter_depth not whole Hz");
    v[SUB_P_FILTER_MODE] = pr.filter_mode;
    v[SUB_P_CUTOFF] = pr.filter_cutoff;
    v[SUB_P_RESONANCE] = pr.filter_resonance;
    v[SUB_P_ENV_CUTOFF] = pr.filter_env_amount;

    for (uint32_t p = 0; p < SUB_P_COUNT; p++) {
        const ParamDescriptor &d = SubtractiveModule::kDescriptors[p];
        if (v[p] < d.min || v[p] > d.max) fail(i, d.name);
    }
}

// The render constants a preset implies, derived directly from its fields --
// the reference the cooked patch must reproduce exactly.
void check_lossless(uint32_t i, const VoicePreset &pr, const SubCookedPatch &c) {
    const bool has_filter = pr.filter_mode != FILTER_OFF;
    const bool has_lfo = pr.lfo_rate != 0.0f;
    if (c.waveform != pr.waveform) fail(i, "cooked waveform");
    if (pr.waveform == WAVE_SAMPLE && c.sample != pr.sample) fail(i, "cooked sample");
    if (c.duty_cycle != pr.duty_cycle) fail(i, "cooked duty");
    if (c.has_lfo != has_lfo) fail(i, "cooked has_lfo");
    if (c.lfo_phase_inc != (has_lfo ? pr.lfo_rate / (float)SAMPLE_RATE : 0.0f)) fail(i, "cooked lfo_phase_inc");
    if (c.lfo_depth_q15 != (int16_t)(pr.lfo_depth * 32767.0f)) fail(i, "cooked lfo_depth_q15");
    if (c.lfo_pitch_q15 != (int16_t)(pr.lfo_pitch_depth * 32767.0f)) fail(i, "cooked lfo_pitch_q15");
    if (c.lfo_pwm_q15 != (int16_t)(pr.lfo_pwm_depth * 512.0f)) fail(i, "cooked lfo_pwm_q15");
    if (c.lfo_filt_hz != (int16_t)pr.lfo_filter_depth) fail(i, "cooked lfo_filt_hz");
    if (c.filter_mode != pr.filter_mode) fail(i, "cooked filter_mode");
    if (c.filter_cutoff != pr.filter_cutoff) fail(i, "cooked filter_cutoff");
    if (c.filter_env_amount != pr.filter_env_amount) fail(i, "cooked filter_env_amount");
    if (c.filter_q != (has_filter ? svf_compute_q(pr.filter_resonance) : 0)) fail(i, "cooked filter_q");
    if (c.f_half_seed != (has_filter ? (float)svf_compute_f_half((int32_t)pr.filter_cutoff) : 0.0f))
        fail(i, "cooked f_half_seed");
}

std::string generate() {
    std::string out =
        "// GENERATED by tools/host_render/gen_subtractive_bank.cpp from presets.h -- do not hand-edit.\n"
        "// The subtractive factory bank: stored-format Patches, compiled in, read-only.\n"
        "#pragma once\n\n"
        "#include \"patch/stored_format.h\"\n"
        "#include <cstdint>\n\n";

    constexpr uint32_t kSize = patch_stored_size(SubtractiveModule::kDescriptors);
    char line[128];
    for (uint32_t i = 0; i < PRESET_COUNT; i++) {
        int32_t v[SUB_P_COUNT];
        to_values(i, presets[i], v);
        SubCookedPatch c{};
        SubtractiveModule::cook(v, c);
        check_lossless(i, presets[i], c);

        uint8_t bytes[kSize];
        patch_encode(SubtractiveModule::kModuleId, SubtractiveModule::kSchemaVersion, preset_names[i],
                     SubtractiveModule::kDescriptors, v, bytes, kSize);

        snprintf(line, sizeof line, "// %u: %s\nstatic const uint8_t kSubFactoryPatch%u[] = {", i, preset_names[i], i);
        out += line;
        for (uint32_t b = 0; b < kSize; b++) {
            snprintf(line, sizeof line, "%s0x%02x,", (b % 12 == 0) ? "\n    " : " ", bytes[b]);
            out += line;
        }
        out += "\n};\n\n";
    }

    out += "static const StoredPatchRef kSubFactoryBank[] = {\n";
    for (uint32_t i = 0; i < PRESET_COUNT; i++) {
        snprintf(line, sizeof line, "    { kSubFactoryPatch%u, sizeof kSubFactoryPatch%u },\n", i, i);
        out += line;
    }
    out += "};\n";
    snprintf(line, sizeof line, "static constexpr uint32_t kSubFactoryCount = %u;\n", (unsigned)PRESET_COUNT);
    out += line;
    return out;
}

}  // namespace

int main(int argc, char **argv) {
    bool check = argc == 3 && !strcmp(argv[1], "--check");
    if (!(argc == 2 || check)) {
        fprintf(stderr, "usage: %s <out.h> | --check <file.h>\n", argv[0]);
        return 2;
    }
    const char *path = argv[argc - 1];
    std::string text = generate();
    if (!g_ok) return 1;

    if (check) {
        FILE *f = fopen(path, "rb");
        if (!f) { perror(path); return 1; }
        std::string existing;
        char buf[4096];
        size_t n;
        while ((n = fread(buf, 1, sizeof buf, f)) > 0) existing.append(buf, n);
        fclose(f);
        bool fresh = existing == text;
        printf(fresh ? "factory bank up to date\nALL CHECKS PASSED\n"
                     : "FAIL %s is stale -- regenerate with gen_subtractive_bank\nCHECKS FAILED\n", path);
        return fresh ? 0 : 1;
    }

    FILE *f = fopen(path, "wb");
    if (!f) { perror(path); return 1; }
    fwrite(text.data(), 1, text.size(), f);
    fclose(f);
    printf("wrote %u patches to %s\n", (unsigned)PRESET_COUNT, path);
    return 0;
}
