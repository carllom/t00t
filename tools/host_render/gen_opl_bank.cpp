// Generates src/engines/opl/factory_bank.h -- the OPL factory bank as
// stored-format Patches -- from the const patch table in
// src/engines/opl/patches.h.
//
//   gen_opl_bank <out.h>            # write the header
//   gen_opl_bank --check <file.h>   # exit 1 if <file.h> is stale
//
// Each patch is converted to Descriptor values, and the conversion is
// checked to be lossless: cooking the values must give back the patch's
// own register fields and the routing it resolves to.

#include "opl_module.h"
#include "patches.h"
#include "patch/stored_format.h"

#include <cstdio>
#include <cstring>
#include <string>

namespace {

bool g_ok = true;

void fail(uint32_t i, const char *what) {
    fprintf(stderr, "patch %u (%s): %s\n", i, OPL_PATCHES[i]->name, what);
    g_ok = false;
}

void to_values(uint32_t i, const OplPatch &pr, int32_t (&v)[OPL_P_COUNT]) {
    for (uint32_t o = 0; o < OPL_NUM_OPS; o++) {
        const OplOpParams &op = pr.op[o];
        v[opl_op_param(o, OPL_OP_MULT)] = op.mult;
        v[opl_op_param(o, OPL_OP_KSL)] = op.ksl;
        v[opl_op_param(o, OPL_OP_TL)] = op.tl;
        v[opl_op_param(o, OPL_OP_AR)] = op.ar;
        v[opl_op_param(o, OPL_OP_DR)] = op.dr;
        v[opl_op_param(o, OPL_OP_SL)] = op.sl;
        v[opl_op_param(o, OPL_OP_RR)] = op.rr;
        v[opl_op_param(o, OPL_OP_EGT)] = op.egt ? 1 : 0;
        v[opl_op_param(o, OPL_OP_KSR)] = op.ksr ? 1 : 0;
        v[opl_op_param(o, OPL_OP_WAVE)] = op.ws;
    }
    v[OPL_P_ALGORITHM] = pr.algorithm;
    v[OPL_P_FEEDBACK] = pr.feedback;
    for (uint32_t p = 0; p < OPL_P_COUNT; p++) {
        const ParamDescriptor &d = OplModule::kDescriptors[p];
        if (v[p] < d.min || v[p] > d.max) fail(i, d.name);
    }
}

bool same_op(const OplOpParams &a, const OplOpParams &b) {
    return a.mult == b.mult && a.ksl == b.ksl && a.tl == b.tl && a.ar == b.ar && a.dr == b.dr &&
           a.sl == b.sl && a.rr == b.rr && a.egt == b.egt && a.ksr == b.ksr && a.ws == b.ws;
}

void check_lossless(uint32_t i, const OplPatch &pr, const OplCookedPatch &c) {
    for (uint32_t o = 0; o < OPL_NUM_OPS; o++) {
        if (!same_op(c.patch.op[o], pr.op[o])) fail(i, "cooked operator");
    }
    if (c.patch.feedback != pr.feedback) fail(i, "cooked feedback");
    if (c.patch.algorithm != pr.algorithm) fail(i, "cooked algorithm");
    FmRouting want{};
    opl_resolve_routing(pr, want);
    if (memcmp(&want, &c.routing, sizeof want) != 0) fail(i, "cooked routing");
}

std::string generate() {
    std::string out =
        "// GENERATED by tools/host_render/gen_opl_bank.cpp from patches.h -- do not hand-edit.\n"
        "// The OPL factory bank: stored-format Patches, compiled in, read-only.\n"
        "#pragma once\n\n"
        "#include \"patch/stored_format.h\"\n"
        "#include <cstdint>\n\n";

    constexpr uint32_t kSize = patch_stored_size(OplModule::kDescriptors);
    char line[128];
    for (uint32_t i = 0; i < OPL_PATCH_COUNT; i++) {
        const OplPatch &pr = *OPL_PATCHES[i];
        int32_t v[OPL_P_COUNT];
        to_values(i, pr, v);
        OplCookedPatch c{};
        OplModule::cook(v, c);
        check_lossless(i, pr, c);
        if (strlen(pr.name) > kPatchNameLen) fail(i, "name longer than a stored name");

        uint8_t bytes[kSize];
        patch_encode(OplModule::kModuleId, OplModule::kSchemaVersion, pr.name, OplModule::kDescriptors, v, bytes,
                     kSize);
        snprintf(line, sizeof line, "// %u: %s\nstatic const uint8_t kOplFactoryPatch%u[] = {", i, pr.name, i);
        out += line;
        for (uint32_t b = 0; b < kSize; b++) {
            snprintf(line, sizeof line, "%s0x%02x,", (b % 12 == 0) ? "\n    " : " ", bytes[b]);
            out += line;
        }
        out += "\n};\n\n";
    }
    out += "static const StoredPatchRef kOplFactoryBank[] = {\n";
    for (uint32_t i = 0; i < OPL_PATCH_COUNT; i++) {
        snprintf(line, sizeof line, "    { kOplFactoryPatch%u, sizeof kOplFactoryPatch%u },\n", i, i);
        out += line;
    }
    out += "};\n";
    snprintf(line, sizeof line, "static constexpr uint32_t kOplFactoryCount = %u;\n", (unsigned)OPL_PATCH_COUNT);
    out += line;
    return out;
}

}  // namespace

int main(int argc, char **argv) {
    bool check = argc == 3 && !strcmp(argv[1], "--check");
    if (!(argc == 2 || check)) {
        fprintf(stderr, "usage: %s <out.h> | --check <file.h>\n", argv[0]);
        return 2;
    }
    const char *path = argv[argc - 1];
    std::string text = generate();
    if (!g_ok) return 1;

    if (check) {
        FILE *f = fopen(path, "rb");
        if (!f) { perror(path); return 1; }
        std::string existing;
        char buf[4096];
        size_t n;
        while ((n = fread(buf, 1, sizeof buf, f)) > 0) existing.append(buf, n);
        fclose(f);
        bool fresh = existing == text;
        printf(fresh ? "factory bank up to date\nALL CHECKS PASSED\n"
                     : "FAIL %s is stale -- regenerate with gen_opl_bank\nCHECKS FAILED\n", path);
        return fresh ? 0 : 1;
    }

    FILE *f = fopen(path, "wb");
    if (!f) { perror(path); return 1; }
    fwrite(text.data(), 1, text.size(), f);
    fclose(f);
    printf("wrote %u patches to %s\n", (unsigned)OPL_PATCH_COUNT, path);
    return 0;
}
